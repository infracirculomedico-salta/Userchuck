-- 2. Tabla de Campañas de Envíos Masivos (WSP_CAMPANAS)
CREATE TABLE wsp_campanas (
    id_campana          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre              VARCHAR2(150) NOT NULL,
    plantilla           VARCHAR2(100) NOT NULL,
    archivo_csv         VARCHAR2(200) NOT NULL,
    total_contactos     NUMBER DEFAULT 0,
    enviados            NUMBER DEFAULT 0,
    exitosos            NUMBER DEFAULT 0,
    errores             NUMBER DEFAULT 0,
    omitidos            NUMBER DEFAULT 0,
    estado              VARCHAR2(30) DEFAULT 'CREADA' NOT NULL,
    log_archivo         VARCHAR2(250),
    creado_por          VARCHAR2(50),
    fecha_creacion      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_finalizacion  TIMESTAMP,
    CONSTRAINT pk_wsp_campanas PRIMARY KEY (id_campana)
);

CREATE INDEX idx_wsp_campanas_plantilla ON wsp_campanas (plantilla);
CREATE INDEX idx_wsp_campanas_fecha ON wsp_campanas (fecha_creacion);


-- 3. Tabla Opcional de Padrón Centralizado de Contactos (WSP_CONTACTOS)
CREATE TABLE wsp_contactos (
    id_contacto             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    matricula               VARCHAR2(30),
    dni                     VARCHAR2(30),
    nombre_completo         VARCHAR2(150) NOT NULL,
    email                   VARCHAR2(150),
    telefono_original       VARCHAR2(50),
    telefono_normalizado    VARCHAR2(30),
    estado_consentimiento   VARCHAR2(20) DEFAULT 'ACEPTO' NOT NULL,
    fecha_consentimiento    VARCHAR2(30),
    fecha_registro          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_wsp_contactos PRIMARY KEY (id_contacto)
);

CREATE INDEX idx_wsp_contactos_tel ON wsp_contactos (telefono_normalizado);
CREATE INDEX idx_wsp_contactos_mat ON wsp_contactos (matricula);
CREATE INDEX idx_wsp_contactos_dni ON wsp_contactos (dni);

COMMIT;
