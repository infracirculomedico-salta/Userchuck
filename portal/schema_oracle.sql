-- 1. Tabla de Usuarios del Portal Web (WSP_USUARIOS)
CREATE TABLE wsp_usuarios (
    id_usuario          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    username            VARCHAR2(50) NOT NULL,
    nombre_completo     VARCHAR2(150) NOT NULL,
    email               VARCHAR2(150),
    rol                 VARCHAR2(20) DEFAULT 'OPERADOR' NOT NULL,
    password_hash       VARCHAR2(128) NOT NULL,
    password_salt       VARCHAR2(64) NOT NULL,
    activo              NUMBER(1) DEFAULT 1 NOT NULL,
    ultimo_acceso       TIMESTAMP,
    fecha_creacion      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_wsp_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uq_wsp_usuarios_username UNIQUE (username),
    CONSTRAINT chk_wsp_usuarios_rol CHECK (rol IN ('ADMIN', 'OPERADOR'))
);

COMMENT ON TABLE wsp_usuarios IS 'Usuarios con acceso al portal de gestión de WhatsApp del Círculo Médico';
COMMENT ON COLUMN wsp_usuarios.rol IS 'ADMIN: Control total y gestión de usuarios. OPERADOR: Envíos y consultas.';

